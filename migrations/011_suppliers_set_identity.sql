-- Agregar la propiedad de autoincremental (IDENTITY)
ALTER TABLE suppliers 
ALTER COLUMN supplierid ADD GENERATED BY DEFAULT AS IDENTITY;
-- Sincronizar el contador interno con el ID más alto existente
SELECT setval(
    pg_get_serial_sequence('suppliers', 'supplierid'), 
    coalesce(max(supplierid), 0)
) 
FROM suppliers;